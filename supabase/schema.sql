-- CRM de prospecção: tabelas no Supabase (Postgres).
-- Rodar uma vez no SQL Editor do Supabase. Pode rodar de novo: nada é recriado se já existir.
--
-- Segurança: o CRM conecta direto no Postgres pelo servidor (DATABASE_URL), nunca pela
-- chave publishable. Por isso o RLS fica ligado SEM políticas e os papéis anon/authenticated
-- perdem acesso: ninguém lê nem grava os leads pela API pública do Supabase.

-- Datas e horas ficam no horário de Brasília, como o CRM sempre gravou.
create or replace function public.agora() returns timestamp(0)
  language sql stable as $$ select (now() at time zone 'America/Sao_Paulo')::timestamp(0) $$;

create table if not exists public.stages (
  id        bigint generated by default as identity primary key,
  name      text    not null,
  position  integer not null,
  kind      text    not null default 'open' check (kind in ('open', 'won', 'lost'))
);

create table if not exists public.searches (
  id              bigint generated by default as identity primary key,
  scraper_job_id  text    not null unique,
  label           text    not null default '',
  keywords        jsonb   not null default '[]',
  city            text    not null default '',
  depth           integer not null default 0,
  max_time        integer not null default 900,
  status          text    not null,
  found           integer not null default 0,
  imported        integer not null default 0,
  updated         integer not null default 0,
  progress        integer not null default 0,
  error           text    not null default '',
  created_at      timestamp(0) not null default public.agora(),
  finished_at     timestamp(0)
);

create table if not exists public.leads (
  id                   bigint generated by default as identity primary key,
  place_id             text unique,
  name                 text    not null,
  category             text    not null default '',
  phone                text    not null default '',
  whatsapp             text    not null default '',
  whatsapp_source      text    not null default '',
  email                text    not null default '',
  instagram            text    not null default '',
  facebook             text    not null default '',
  website              text    not null default '',
  website_kind         text    not null default '',
  address              text    not null default '',
  city                 text    not null default '',
  maps_link            text    not null default '',
  rating               double precision,
  reviews              integer not null default 0,
  priority             text    not null default 'BAIXA',
  needs_site           text    not null default 'NÃO',
  site_argument        text    not null default '',
  marketing_arguments  jsonb   not null default '[]',
  stage_id             bigint  not null references public.stages(id),
  owner                text    not null default '',
  value                double precision,
  next_followup        date,
  last_contact_at      timestamp(0),
  lat                  double precision,
  lng                  double precision,
  search_id            bigint references public.searches(id) on delete set null,
  raw                  jsonb   not null default '{}',
  created_at           timestamp(0) not null default public.agora(),
  updated_at           timestamp(0) not null default public.agora()
);
create index if not exists leads_stage    on public.leads(stage_id);
create index if not exists leads_followup on public.leads(next_followup);
create index if not exists leads_search   on public.leads(search_id);

create table if not exists public.templates (
  id    bigint generated by default as identity primary key,
  name  text not null,
  body  text not null
);

create table if not exists public.settings (
  key    text primary key,
  value  text not null
);

-- Histórico: sem chave estrangeira de propósito (o lead some, o histórico fica).
create table if not exists public.lead_log (
  id          bigint generated by default as identity primary key,
  lead_id     bigint not null,
  lead_name   text   not null default '',
  action      text   not null,
  kind        text   not null default '',
  stage_to    bigint,
  text        text   not null default '',
  changes     jsonb  not null default '{}',
  author      text   not null default '',
  created_at  timestamp(0) not null default public.agora()
);
create index if not exists lead_log_lead    on public.lead_log(lead_id);
create index if not exists lead_log_created on public.lead_log(created_at);

create table if not exists public.events (
  id            bigint generated by default as identity primary key,
  lead_id       bigint references public.leads(id) on delete set null,
  lead_name     text    not null default '',
  title         text    not null,
  type          text    not null default 'reuniao',
  starts_at     timestamp(0) not null,
  duration_min  integer not null default 60,
  owner         text    not null default '',
  notes         text    not null default '',
  status        text    not null default 'agendado',
  created_at    timestamp(0) not null default public.agora(),
  updated_at    timestamp(0) not null default public.agora()
);
create index if not exists events_start on public.events(starts_at);
create index if not exists events_lead  on public.events(lead_id);

-- Fecha a API pública: só o servidor do CRM (conexão direta) acessa.
do $$
declare t text;
begin
  foreach t in array array['stages','searches','leads','templates','settings','lead_log','events'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;
revoke execute on function public.agora() from anon, authenticated;

